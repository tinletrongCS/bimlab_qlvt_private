-- ---------------------------------------------------------------------------
-- Tài liệu/biên bản gắn với phiếu bàn giao. không gắn trực tiếp với 1 tài sản
-- Lưu metadata/object_key, file vật lý lưu ở MinIO
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS asset.asset_transfer_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_header_id BIGINT NOT NULL,
    document_type VARCHAR(40) NOT NULL DEFAULT 'HANDOVER_MINUTES',
    document_status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    file_name VARCHAR(255) NOT NULL,
    object_key VARCHAR(500) NOT NULL,
    content_type VARCHAR(120) NULL,
    size_bytes BIGINT NULL,
    uploaded_by VARCHAR(200) NULL,
    created_at TIMESTAMP NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_asset_transfer_documents_object_key
    ON asset.asset_transfer_documents(object_key);
CREATE INDEX IF NOT EXISTS idx_asset_transfer_documents_header
    ON asset.asset_transfer_documents(transfer_header_id);
CREATE INDEX IF NOT EXISTS idx_asset_transfer_documents_type
    ON asset.asset_transfer_documents(document_type);

-- ---------------------------------------------------------------------------
-- Các bước xác nhận/ ký của bàn giao 
