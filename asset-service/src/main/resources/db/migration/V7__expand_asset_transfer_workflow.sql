    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    signature_method VARCHAR(30) NULL,
    signature_document_id BIGINT NULL,
    confirmed_at TIMESTAMP NULL,
    note VARCHAR(1000) NULL,
    created_at TIMESTAMP NOT NULL DEFAULT now(),
    updated_at TIMESTAMP NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_asset_transfer_confirmations_header
    ON asset.asset_transfer_confirmations(transfer_header_id);
CREATE INDEX IF NOT EXISTS idx_asset_transfer_confirmations_status
    ON asset.asset_transfer_confirmations(status);
CREATE INDEX IF NOT EXISTS idx_asset_transfer_confirmations_employee
    ON asset.asset_transfer_confirmations(confirmer_employee_id);
