-- ---------------------------------------------------------------------------
-- Constraints dat trong DO block de migration chay lai an toan tren DB da ton tai.
-- ---------------------------------------------------------------------------

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE connamespace = 'asset'::regnamespace
          AND conname = 'ck_asset_transfer_headers_status'
    ) THEN
    -- TRẠNG THÁI BÀN GIAO
        ALTER TABLE asset.asset_transfer_headers
            ADD CONSTRAINT ck_asset_transfer_headers_status
            CHECK (status IN (
                'DRAFT',
                'PENDING_CONFIRM',
                'PENDING_APPROVAL',
                'APPROVED',
                'COMPLETED',
                'REJECTED',
                'CANCELLED'
            )) NOT VALID;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE connamespace = 'asset'::regnamespace
          AND conname = 'ck_asset_transfer_headers_type'
    ) THEN
    -- CHECK RÀNG BUỘC TRẠNG THÁI PHIẾU ĐĂNG KÝ 
        ALTER TABLE asset.asset_transfer_headers
            ADD CONSTRAINT ck_asset_transfer_headers_type
            CHECK (transfer_type IN (
                'ASSIGN',
                'TRANSFER',
                'REVOKE',
                'REASSIGN',
                'BRANCH_TRANSFER',
                'DEPARTMENT_TRANSFER',
                'EMPLOYEE_TRANSFER',
                'PROJECT_TRANSFER',
                'WAREHOUSE_TRANSFER'
            )) NOT VALID;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE connamespace = 'asset'::regnamespace
          AND conname = 'fk_asset_transfer_documents_header'
    ) THEN
        ALTER TABLE asset.asset_transfer_documents
            ADD CONSTRAINT fk_asset_transfer_documents_header
            FOREIGN KEY (transfer_header_id)
            REFERENCES asset.asset_transfer_headers(id)
            ON DELETE CASCADE NOT VALID;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE connamespace = 'asset'::regnamespace
          AND conname = 'ck_asset_transfer_documents_type'
    ) THEN
        ALTER TABLE asset.asset_transfer_documents
            ADD CONSTRAINT ck_asset_transfer_documents_type
            CHECK (document_type IN (
                'HANDOVER_MINUTES',
                'SIGNED_MINUTES',
                'IMAGE',
                'ATTACHMENT',
                'OTHER'
            )) NOT VALID;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE connamespace = 'asset'::regnamespace
          AND conname = 'ck_asset_transfer_documents_status'
    ) THEN
        ALTER TABLE asset.asset_transfer_documents
            ADD CONSTRAINT ck_asset_transfer_documents_status
            CHECK (document_status IN ('ACTIVE', 'REVOKED')) NOT VALID;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE connamespace = 'asset'::regnamespace
          AND conname = 'ck_asset_transfer_documents_size_non_negative'
    ) THEN
        ALTER TABLE asset.asset_transfer_documents
            ADD CONSTRAINT ck_asset_transfer_documents_size_non_negative
            CHECK (size_bytes IS NULL OR size_bytes >= 0) NOT VALID;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE connamespace = 'asset'::regnamespace
          AND conname = 'fk_asset_transfer_confirmations_header'
    ) THEN
        ALTER TABLE asset.asset_transfer_confirmations
            ADD CONSTRAINT fk_asset_transfer_confirmations_header
            FOREIGN KEY (transfer_header_id)
            REFERENCES asset.asset_transfer_headers(id)
            ON DELETE CASCADE NOT VALID;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE connamespace = 'asset'::regnamespace
          AND conname = 'fk_asset_transfer_confirmations_signature_document'
    ) THEN
        ALTER TABLE asset.asset_transfer_confirmations
            ADD CONSTRAINT fk_asset_transfer_confirmations_signature_document
            FOREIGN KEY (signature_document_id)
            REFERENCES asset.asset_transfer_documents(id)
            ON DELETE SET NULL NOT VALID;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE connamespace = 'asset'::regnamespace
          AND conname = 'ck_asset_transfer_confirmations_role'
    ) THEN
        ALTER TABLE asset.asset_transfer_confirmations
            ADD CONSTRAINT ck_asset_transfer_confirmations_role
            CHECK (confirmation_role IN (
                'REQUESTER',
                'HANDOVER',
                'RECEIVER',
                'MANAGER',
                'WAREHOUSE',
                'ACCOUNTING',
                'ADMIN'
            )) NOT VALID;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE connamespace = 'asset'::regnamespace
          AND conname = 'ck_asset_transfer_confirmations_status'
    ) THEN
        ALTER TABLE asset.asset_transfer_confirmations
            ADD CONSTRAINT ck_asset_transfer_confirmations_status
            CHECK (status IN (
                'PENDING',
                'APPROVED',
                'REJECTED',
                'CANCELLED',
                'SKIPPED'
            )) NOT VALID;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE connamespace = 'asset'::regnamespace
          AND conname = 'fk_asset_transfers_header'
    ) THEN
        ALTER TABLE asset.asset_transfers
            ADD CONSTRAINT fk_asset_transfers_header
            FOREIGN KEY (transfer_header_id)
            REFERENCES asset.asset_transfer_headers(id)
            ON DELETE CASCADE NOT VALID;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE connamespace = 'asset'::regnamespace
          AND conname = 'ck_asset_transfers_line_status'
    ) THEN
        ALTER TABLE asset.asset_transfers
            ADD CONSTRAINT ck_asset_transfers_line_status
            CHECK (line_status IN (
                'PENDING',
                'APPROVED',
                'COMPLETED',
                'REJECTED',
                'CANCELLED'
            )) NOT VALID;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE connamespace = 'asset'::regnamespace
          AND conname = 'ck_asset_transfers_book_value_non_negative'
    ) THEN
        ALTER TABLE asset.asset_transfers
            ADD CONSTRAINT ck_asset_transfers_book_value_non_negative
            CHECK (book_value_at_transfer IS NULL OR book_value_at_transfer >= 0) NOT VALID;
    END IF;
END $$;

-- ---------------------------------------------------------------------------
-- Backfill du lieu cu: moi transfer cu thanh mot phieu LEGACY rieng.
-- Backend moi co the gom nhieu dong vao cung transfer_header_id.
-- ---------------------------------------------------------------------------

INSERT INTO asset.asset_transfer_headers (
    transfer_code,
    title,
    transfer_type,
    status,
    requested_by,
    approved_by,
    from_employee_id,
    to_employee_id,
    from_department_id,
    to_department_id,
    from_site_id,
    to_site_id,
    from_project_id,
    to_project_id,
    transfer_date,
    completed_at,
    reason,
    created_at,
    updated_at
)
SELECT
    'LEGACY-' || t.id,
    'Phieu ban giao tao tu du lieu cu #' || t.id,
    t.transfer_type,
    'COMPLETED',
    t.performed_by,
    t.approved_by,
    t.from_employee_id,
    t.to_employee_id,
    t.from_department_id,
    t.to_department_id,
    t.from_site_id,
    t.to_site_id,
    t.from_project_id,
    t.to_project_id,
    t.transfer_date,
    COALESCE(t.created_at, now()),
    t.reason,
    COALESCE(t.created_at, now()),
    now()
FROM asset.asset_transfers t
WHERE t.transfer_header_id IS NULL
  AND NOT EXISTS (
      SELECT 1
      FROM asset.asset_transfer_headers h
      WHERE h.transfer_code = 'LEGACY-' || t.id
  );

UPDATE asset.asset_transfers t
SET transfer_header_id = h.id,
    line_no = COALESCE(t.line_no, 1),
    line_status = COALESCE(t.line_status, 'COMPLETED')
FROM asset.asset_transfer_headers h
WHERE t.transfer_header_id IS NULL
  AND h.transfer_code = 'LEGACY-' || t.id;

COMMENT ON TABLE asset.asset_transfer_headers IS
    'Header/phieu ban giao tai san. Mot phieu co the gom nhieu dong asset_transfers.';
COMMENT ON TABLE asset.asset_transfer_documents IS
    'Tai lieu va bien ban cua phieu ban giao, luu metadata file/object_key MinIO.';
COMMENT ON TABLE asset.asset_transfer_confirmations IS
    'Cac buoc xac nhan/ky cua phieu ban giao theo vai tro va nguoi xac nhan.';
COMMENT ON COLUMN asset.asset_transfers.transfer_header_id IS
    'Lien ket dong transfer cu voi header phieu ban giao moi.';
