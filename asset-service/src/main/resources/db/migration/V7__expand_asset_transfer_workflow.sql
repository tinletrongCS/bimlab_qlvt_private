--
--   1. Tao bang header cho "phieu ban giao" de gom nhieu tai san vao mot phieu.
--   2. Giu bang asset.asset_transfers hien co lam dong chi tiet tai san,
--      tranh pha vo API/service cu dang ghi theo tung asset_id.
