CREATE TABLE IF NOT EXISTS asset.asset_transfer_confirmations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_header_id BIGINT NOT NULL,
    confirmation_role VARCHAR(40) NOT NULL,
    confirmer_employee_id BIGINT NULL,
    confirmer_username VARCHAR(120) NULL,
